#!/usr/bin/env python
"""Launcher icon (run with `python -I tools/make_icon.py [--factory <512 png path>]`).

Factory rule (2026-10-21): an adaptive icon of the app's own, flat, no words; foreground a vector drawable,
background one solid colour no other factory app uses (others: furniture-fit blue #3D8BFF, jieyan slate #20262A).

Foreground: a T. rex side silhouette traced from the bundled model's render (res/drawable-nodpi/sil_trex.png)
with a person at the same scale and the yellow floor tape under both: "how big is it next to you".
Writes res/drawable/ic_launcher_foreground.xml (vector), res/values/ic_launcher_background.xml (colour),
the PICO 3D icon layers (res/drawable/icon_3d_*) and the 512 px factory PNG.
"""
import argparse
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
BG = "#2E6B4F"  # jungle green: this app only
SAND = "#F3E8CF"
CYAN = "#7FD8FF"
YELLOW = "#FFD24A"
INK = "#2A2108"

# Layout in the 108 x 108 dp adaptive viewport; the safe zone is the central 66 dp circle.
VIEW = 108.0
REX_W = 48.0
REX_X = 33.0
GROUND = 62.0
METRE = REX_W / 12.3
PERSON_X = 27.0


def trace_rex():
    """Outer contour(s) of the silhouette as a polygon list in viewport units, simplified."""
    sil = Image.open(os.path.join(RES, "drawable-nodpi", "sil_trex.png")).convert("RGBA")
    a = np.asarray(sil.getchannel("A"), dtype=float)
    a = np.pad(a, 2)
    cs = plt.contour(a, levels=[128])
    plt.close("all")
    k = REX_W / sil.width
    h = sil.height * k
    polys = []
    for seg in cs.allsegs[0]:
        if len(seg) < 12:
            continue
        pts = [((x - 2) * k + REX_X, (y - 2) * k + GROUND - h) for x, y in seg]
        # a closed contour starts and ends on the same point: simplify its two halves
        mid = len(pts) // 2
        pts = simplify(pts[: mid + 1], 0.18)[:-1] + simplify(pts[mid:], 0.18)
        if len(pts) >= 4:
            polys.append(pts)
    return polys


def simplify(pts, eps):
    """Douglas-Peucker."""
    if len(pts) < 3:
        return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1 - x0, y1 - y0
    n = (dx * dx + dy * dy) ** 0.5 or 1e-9
    best, idx = 0.0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x1 * y0 - y1 * x0) / n
        if d > best:
            best, idx = d, i
    if best > eps:
        return simplify(pts[: idx + 1], eps)[:-1] + simplify(pts[idx:], eps)
    return [pts[0], pts[-1]]


def path_data(polys):
    return " ".join("M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in p) + " Z" for p in polys)


def rrect(x0, y0, x1, y1, r):
    return (
        f"M{x0 + r:.2f},{y0:.2f} H{x1 - r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x1:.2f},{y0 + r:.2f} V{y1 - r:.2f} "
        f"A{r:.2f},{r:.2f} 0 0 1 {x1 - r:.2f},{y1:.2f} H{x0 + r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x0:.2f},{y1 - r:.2f} "
        f"V{y0 + r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x0 + r:.2f},{y0:.2f} Z"
    )


def person():
    """A 1.7 m figure at the T. rex's scale: head circle, body, two legs."""
    h = 1.7 * METRE
    head = h * 0.15
    bw = h * 0.27
    x = PERSON_X
    top = GROUND - h
    cx = x + bw / 2
    r = head / 2
    circle = f"M{cx - r:.2f},{top + r:.2f} A{r:.2f},{r:.2f} 0 1 1 {cx + r:.2f},{top + r:.2f} A{r:.2f},{r:.2f} 0 1 1 {cx - r:.2f},{top + r:.2f} Z"
    body = rrect(x, top + head * 1.12, x + bw, GROUND - h * 0.45, bw * 0.3)
    lw = bw * 0.42
    legs = rrect(x + bw * 0.04, GROUND - h * 0.5, x + bw * 0.04 + lw, GROUND, lw * 0.4) + " " + rrect(x + bw * 0.96 - lw, GROUND - h * 0.5, x + bw * 0.96, GROUND, lw * 0.4)
    return circle + " " + body + " " + legs


def tape():
    t = 2.2
    x0, x1 = PERSON_X - 3.0, REX_X + REX_W + 2.0
    band = rrect(x0, GROUND + 1.6, x1, GROUND + 1.6 + t, t / 2)
    ticks = []
    for i in range(1, 13):
        x = REX_X + REX_W - i * METRE
        if x0 + 1 < x < x1 - 1:
            ticks.append(f"M{x - 0.3:.2f},{GROUND + 1.6:.2f} H{x + 0.3:.2f} V{GROUND + 1.6 + t * 0.55:.2f} H{x - 0.3:.2f} Z")
    return band, " ".join(ticks)


def write_vector(polys):
    band, ticks = tape()
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py: a T. rex traced from the bundled model, a person at the same scale,
     the yellow floor tape under both. 108 dp adaptive foreground; the drawing stays in the 66 dp safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{SAND}" android:pathData="{path_data(polys)}" />
    <path android:fillColor="{CYAN}" android:pathData="{person()}" />
    <path android:fillColor="{YELLOW}" android:pathData="{band}" />
    <path android:fillColor="{INK}" android:pathData="{ticks}" />
</vector>
"""
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(xml)
    with open(os.path.join(RES, "values", "ic_launcher_background.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Launcher background: jungle green, used by no other factory app (tools/make_icon.py). -->
    <color name="ic_launcher_background">{BG}</color>
</resources>
""")


def raster(polys, size, background=True):
    """The same drawing as a bitmap (3D icon layers, the flat mipmap, the factory PNG)."""
    s = size / VIEW
    img = Image.new("RGBA", (size, size), BG if background else (0, 0, 0, 0))
    big = 4
    hi = Image.new("RGBA", (size * big, size * big), (0, 0, 0, 0))
    d = ImageDraw.Draw(hi)
    k = s * big
    for p in polys:
        d.polygon([(x * k, y * k) for x, y in p], fill=SAND)
    h = 1.7 * METRE
    head = h * 0.15
    bw = h * 0.27
    x, top = PERSON_X, GROUND - h
    d.ellipse([(x + bw / 2 - head / 2) * k, top * k, (x + bw / 2 + head / 2) * k, (top + head) * k], fill=CYAN)
    d.rounded_rectangle([x * k, (top + head * 1.12) * k, (x + bw) * k, (GROUND - h * 0.45) * k], radius=bw * 0.3 * k, fill=CYAN)
    lw = bw * 0.42
    d.rounded_rectangle([(x + bw * 0.04) * k, (GROUND - h * 0.5) * k, (x + bw * 0.04 + lw) * k, GROUND * k], radius=lw * 0.4 * k, fill=CYAN)
    d.rounded_rectangle([(x + bw * 0.96 - lw) * k, (GROUND - h * 0.5) * k, (x + bw * 0.96) * k, GROUND * k], radius=lw * 0.4 * k, fill=CYAN)
    t = 2.2
    x0, x1 = PERSON_X - 3.0, REX_X + REX_W + 2.0
    d.rounded_rectangle([x0 * k, (GROUND + 1.6) * k, x1 * k, (GROUND + 1.6 + t) * k], radius=t / 2 * k, fill=YELLOW)
    for i in range(1, 13):
        xx = REX_X + REX_W - i * METRE
        if x0 + 1 < xx < x1 - 1:
            d.rectangle([(xx - 0.3) * k, (GROUND + 1.6) * k, (xx + 0.3) * k, (GROUND + 1.6 + t * 0.55) * k], fill=INK)
    img.alpha_composite(hi.resize((size, size), Image.LANCZOS))
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--factory", default=None)
    a = ap.parse_args()
    polys = trace_rex()
    write_vector(polys)
    fg = raster(polys, 1024, background=False)
    Image.new("RGBA", (1024, 1024), BG).save(os.path.join(RES, "drawable", "icon_3d_layer_0.png"))
    fg.save(os.path.join(RES, "drawable", "icon_3d_layer_1.png"))
    Image.new("RGBA", (1024, 1024), (255, 255, 255, 255)).save(os.path.join(RES, "drawable", "icon_3d_sdf_0.png"))
    sdf = Image.new("RGBA", (1024, 1024), (255, 255, 255, 0))
    sdf.putalpha(fg.getchannel("A"))
    sdf.save(os.path.join(RES, "drawable", "icon_3d_sdf_1.png"))
    old = os.path.join(RES, "drawable", "ic_launcher_foreground.png")
    if os.path.exists(old):
        os.remove(old)
    if a.factory:
        raster(polys, 512).save(a.factory)
        print("wrote", a.factory)
    print("contours", len(polys), "points", sum(len(p) for p in polys))


if __name__ == "__main__":
    main()
